#!/usr/bin/env node
/**
 * Write site/data/skill-dates.json from git history (UTC ISO).
 * Committed so Docker builds without .git get real per-skill updated_at.
 *
 * After squash or rebase, git dates for skill folders can change — re-run this
 * script and commit the result, or CI `--check` fails.
 *
 * Usage:
 *   node scripts/generate-skill-dates.mjs          # write file
 *   node scripts/generate-skill-dates.mjs --check  # exit 1 if stale
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { listPublishableSkillDirs } from "../src/lib/skill-sources.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(siteRoot, "..");
const outPath = path.join(siteRoot, "data", "skill-dates.json");
const checkOnly = process.argv.includes("--check");

function skillDateFromGit(name) {
  const out = execFileSync(
    "git",
    ["log", "-1", "--format=%cI", "--", name],
    { cwd: repoRoot, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
  ).trim();
  if (!out) {
    throw new Error(`no git history for skill folder: ${name}`);
  }
  const d = new Date(out);
  if (Number.isNaN(d.getTime())) {
    throw new Error(`invalid git date for ${name}: ${out}`);
  }
  return d.toISOString();
}

function buildPayload() {
  const skills = {};
  for (const name of listPublishableSkillDirs(repoRoot)) {
    skills[name] = skillDateFromGit(name);
  }
  return {
    $comment:
      "Committed per-skill updated_at (UTC). Regenerated by site/scripts/generate-skill-dates.mjs; CI fails if stale vs git. Re-run after squash/rebase.",
    generated_from: "git log -1 --format=%cI -- <skill>",
    skills,
  };
}

const payload = buildPayload();
const next = JSON.stringify(payload, null, 2) + "\n";

if (checkOnly) {
  if (!fs.existsSync(outPath)) {
    console.error(`skill-dates.json missing at ${outPath}`);
    process.exit(1);
  }
  const prev = fs.readFileSync(outPath, "utf8");
  if (prev !== next) {
    console.error(
      "skill-dates.json is stale vs git. Run: node site/scripts/generate-skill-dates.mjs",
    );
    console.error("--- expected ---");
    console.error(next);
    console.error("--- committed ---");
    console.error(prev);
    process.exit(1);
  }
  console.log(
    `skill-dates.json OK (${Object.keys(payload.skills).length} skill(s))`,
  );
  process.exit(0);
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, next);
console.log(
  `wrote ${outPath} (${Object.keys(payload.skills).length} skill(s))`,
);
